import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const feed=read('functions/api/social-feed.js');
const admin=read('functions/api/admin/social-content.js');
const middleware=read('functions/api/admin/_middleware.js');
const pdp=read('public/tshop-v119.js');
const manager=read('public/seller-social.html');
assert.match(feed,/productId/,'social feed must support product-scoped content');
assert.match(feed,/sale_verified=1/,'public social feed must only join sale-verified products');
assert.match(feed,/databaseReady:false/,'public feed must fail closed without D1');
assert.doesNotMatch(feed,/ผู้ติดตาม|กำลังดู|ล้านวิว|mock|fallbackCreators/i,'public feed must not synthesize social proof');
assert.match(admin,/validTikTokVideo/,'admin API must validate TikTok URLs');
assert.match(admin,/product_required/,'admin API must require product binding');
assert.match(admin,/viewer_count=0,like_count=0/,'admin updates must reset unverified TikTok metrics');
assert.match(admin,/viewer_count,like_count,updated_at\) VALUES\(\?,'video',[\s\S]*0,0/,'admin inserts must not accept social metrics from clients');
assert.match(middleware,/social-content/,'social manager must be protected by catalog permissions');
assert.match(pdp,/\/api\/social-feed\?productId=/,'PDP must fetch product-scoped social content');
assert.match(pdp,/\/api\/reviews\?productId=/,'PDP must fetch real on-site reviews');
assert.match(pdp,/www\.tiktok\.com\/player\/v1/,'PDP must use TikTok player embed');
assert.doesNotMatch(pdp,/content\.viewers|content\.likes|\.followers\.toLocaleString/,'PDP must not render unverified TikTok metrics');
assert.match(manager,/\/api\/staff\/me/,'manager must use staff session');
assert.match(manager,/X-KCH-CSRF/,'manager writes must use staff CSRF token');
assert.match(manager,/\/api\/admin\/social-content/,'manager must use protected social-content endpoint');
assert.match(manager,/แบบร่าง — ยังไม่แสดง/,'manager must support safe draft mode');
assert.match(manager,/เผยแพร่ — แสดงหน้าสินค้า/,'manager must make publishing explicit');
console.log('Social commerce content safety + manager contracts: OK');
