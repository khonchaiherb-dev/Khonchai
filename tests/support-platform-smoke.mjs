import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const migration=read('db/migrations/0023_support_platform.sql');
const api=read('functions/api/support/tickets.js');
const admin=read('functions/api/admin/support-tickets.js');
const html=read('public/support.html');
const js=read('public/support.js');
const selfService=read('public/support-self-service.js');
const selfServiceCss=read('public/support-self-service.css');
for(const token of ['support_tickets','support_messages','support_ticket_events','support_satisfaction'])if(!migration.includes(token))throw new Error(`missing schema ${token}`);
for(const token of ['sla_first_response_due_at','access_code_hash','ticket_access_denied','rate_limited'])if(!api.includes(token))throw new Error(`missing public support capability ${token}`);
for(const token of ['assign_self','pending_customer','internal_note_added','csatAverage'])if(!admin.includes(token))throw new Error(`missing admin support capability ${token}`);
for(const token of ['ศูนย์ช่วยเหลือ','ติดตามเคส','ส่งเรื่องให้ทีมดูแล','SELF-SERVICE KNOWLEDGE BASE','ค้นหาคำตอบก่อนเปิดเคส','support-self-service.js'])if(!html.includes(token))throw new Error(`missing support ui ${token}`);
for(const token of ['track-order','การเก็บเงินปลายทาง','ใบเสร็จออกเมื่อใด','คืนสินค้า','ความเป็นส่วนตัว','data-kb-escalate'])if(!selfService.includes(token))throw new Error(`missing self-service knowledge capability ${token}`);
for(const token of ['kch-kb-grid','kch-kb-article','kch-kb-search'])if(!selfServiceCss.includes(token))throw new Error(`missing self-service knowledge style ${token}`);
if(!js.includes('/api/support/tickets'))throw new Error('support frontend is not connected to API');
console.log('support platform smoke: ok');
