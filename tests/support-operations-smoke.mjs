import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('public/seller-support.html');
const css=read('public/seller-support.css');
const js=read('public/seller-support.js');
const quality=read('public/seller-support-quality.js');
const api=read('functions/api/admin/support-tickets.js');
const auth=read('functions/_lib/staff-auth.js');
const middleware=read('functions/api/admin/_middleware.js');
const headers=read('public/_headers');
const gateway=read('public/seller-center.html');
for(const token of ['Support Operations','CUSTOMER 360','SERVICE LEVEL','Internal note','metric-first-breach','metric-csat','metric-positive','quality-info'])if(!html.includes(token))throw new Error(`missing support console UI: ${token}`);
for(const token of ['grid-template-columns','ticket-card','sla-line','conversation-card'])if(!css.includes(token))throw new Error(`missing support console style: ${token}`);
for(const token of ['/api/admin/support-tickets','support.read','support.manage','assign_self','first_response_breached','setInterval','60000'])if(!js.includes(token))throw new Error(`missing support console behavior: ${token}`);
for(const token of ['metric-csat','metric-positive','csatAverage','satisfaction','60000'])if(!quality.includes(token))throw new Error(`missing CSAT quality monitor: ${token}`);
for(const token of ['supportStats','customerSnapshot','avgFirstResponseMinutes','resolutionBreached','openSupportTickets','recentOrders','csatAverage','csatPositivePct','support_satisfaction','satisfaction_score'])if(!api.includes(token))throw new Error(`missing support API operations capability: ${token}`);
if(!auth.includes("'support.read','support.manage'"))throw new Error('support role permissions missing');
if(!middleware.includes("write?'support.manage':'support.read'"))throw new Error('support API permission boundary missing');
if(!headers.includes('/seller-support.html')||!headers.includes('/seller-support-quality.js'))throw new Error('seller support cache policy missing');
if(!gateway.includes('/seller-support.html'))throw new Error('seller center gateway does not expose support operations');
console.log('support operations smoke: ok');
